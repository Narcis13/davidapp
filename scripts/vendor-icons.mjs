// Vendors a curated set of Lucide icons (ISC licence) for the kit-icon asset and writes the icon data into
// assets/kit-icon.js. Nothing is fetched here: the package is unpacked once by hand, and the SVGs, the licence and
// the version are committed under vendor/lucide/, so the repo rebuilds the asset without a network.
//
//   npm pack lucide-static@1.49.0 && mkdir lucide && tar -xzf lucide-static-1.49.0.tgz -C lucide   (in a scratch dir)
//   node scripts/vendor-icons.mjs --from <scratch>/lucide/package     copy the curated SVGs + LICENSE + README + version, then regenerate
//   node scripts/vendor-icons.mjs                                      regenerate the asset from vendor/lucide/icons
//   node scripts/vendor-icons.mjs --check                              fail when the asset's data is not what the vendored SVGs give
//
// Every element (path, circle, ellipse, rect, line, polyline, polygon) becomes SVG path data on the 24×24 grid, all of
// an icon's elements joined with | into one string: each part is a path of its own (a path's first moveto is absolute even when written m).

import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const VENDOR = join(ROOT, 'vendor', 'lucide');
export const ASSET = join(ROOT, 'assets', 'kit-icon.js');
export const BEGIN = '// <icons> generated by scripts/vendor-icons.mjs from vendor/lucide (do not edit by hand)';
export const END = '// </icons>';

