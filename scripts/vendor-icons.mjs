export const NAMES = Object.values(CURATED).flat();

const num = (v) => Number(Number(v).toFixed(3));
const fmt = (...v) => v.map((x) => String(num(x))).join(' ');

/** The attributes of one element, as { name: string }. */
function attrsOf(text) {
  const out = {};
  for (const m of text.matchAll(/([a-zA-Z][a-zA-Z0-9-]*)="([^"]*)"/g)) out[m[1]] = m[2];
  // an attribute the pattern did not catch would silently draw a shape wrong: count them
  if ((text.match(/=/g) ?? []).length !== Object.keys(out).length) throw new Error(`cannot read the attributes of <${text.trim().slice(0, 60)}>`);
  return out;
}

const ALLOWED = new Set(['d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'width', 'height', 'x1', 'y1', 'x2', 'y2', 'points', 'fill']);

/** One element → path data. Throws on anything the asset could not draw the way Lucide does. */
export function elementToPath(tag, a, name) {
  for (const k of Object.keys(a)) if (!ALLOWED.has(k)) throw new Error(`${name}: <${tag}> has an attribute (${k}) this generator does not convert`);
  if (a.fill && a.fill !== 'currentColor' && a.fill !== 'none') throw new Error(`${name}: <${tag}> has fill="${a.fill}"`);
  const n = (k, d = 0) => (a[k] === undefined ? d : Number(a[k]));
  switch (tag) {
    case 'path': return a.d.replace(/\s+/g, ' ').trim();
    case 'circle': { const r = n('r'); return `M${fmt(n('cx') - r, n('cy'))}a${fmt(r, r, 0, 1, 0, 2 * r, 0)}a${fmt(r, r, 0, 1, 0, -2 * r, 0)}`; }
    case 'ellipse': { const rx = n('rx'), ry = n('ry'); return `M${fmt(n('cx') - rx, n('cy'))}a${fmt(rx, ry, 0, 1, 0, 2 * rx, 0)}a${fmt(rx, ry, 0, 1, 0, -2 * rx, 0)}`; }
    case 'line': return `M${fmt(n('x1'), n('y1'))}L${fmt(n('x2'), n('y2'))}`;
    case 'polyline':
    case 'polygon': {
      const pts = a.points.trim().split(/[\s,]+/).map(Number);
      let d = `M${fmt(pts[0], pts[1])}`;
      for (let i = 2; i < pts.length; i += 2) d += `L${fmt(pts[i], pts[i + 1])}`;
      return tag === 'polygon' ? `${d}Z` : d;
    }
    case 'rect': {
      const x = n('x'), y = n('y'), w = n('width'), h = n('height');
      let rx = a.rx === undefined ? (a.ry === undefined ? 0 : n('ry')) : n('rx');
      let ry = a.ry === undefined ? rx : n('ry');
      rx = Math.min(rx, w / 2); ry = Math.min(ry, h / 2);
      if (!rx && !ry) return `M${fmt(x, y)}h${fmt(w)}v${fmt(h)}h${fmt(-w)}Z`;
      return `M${fmt(x + rx, y)}h${fmt(w - 2 * rx)}a${fmt(rx, ry, 0, 0, 1, rx, ry)}v${fmt(h - 2 * ry)}a${fmt(rx, ry, 0, 0, 1, -rx, ry)}h${fmt(-(w - 2 * rx))}a${fmt(rx, ry, 0, 0, 1, -rx, -ry)}v${fmt(-(h - 2 * ry))}a${fmt(rx, ry, 0, 0, 1, rx, -ry)}Z`;
    }
    default: throw new Error(`${name}: <${tag}> is not converted`);
  }
}

/** A Lucide SVG → one path string for the whole icon. */
export function svgToPath(svg, name) {
  const root = /<svg\b([^>]*)>/.exec(svg);
  if (!root) throw new Error(`${name}: no <svg>`);
  const r = attrsOf(root[1]);
  if (r.viewBox !== '0 0 24 24' || r.fill !== 'none' || r['stroke-linecap'] !== 'round' || r['stroke-linejoin'] !== 'round') throw new Error(`${name}: not drawn the way the rest of the set is (24 grid, stroke only, round caps and joins)`);
  const body = svg.slice(root.index + root[0].length);
  if (/<(g|defs|use|mask|clipPath|style)\b/.test(body)) throw new Error(`${name}: groups and references are not converted`);
  const parts = [];
  for (const m of body.matchAll(/<(path|circle|ellipse|rect|line|polyline|polygon)\b([^>]*?)\/?>/g)) parts.push(elementToPath(m[1], attrsOf(m[2]), name));
  if (!parts.length) throw new Error(`${name}: no shapes`);
  return parts.join('|');
}

/** name → path data for every vendored icon. */
export function vendoredIcons(dir = join(VENDOR, 'icons')) {
  const out = {};
  for (const name of NAMES) out[name] = svgToPath(readFileSync(join(dir, `${name}.svg`), 'utf8'), name);
  return out;
}

/** The generated block of the asset source. */
export function block(icons) {
  const lines = Object.entries(icons).map(([k, d]) => `  '${k}': '${d}',`);
  return `${BEGIN}\nconst ICONS = {\n${lines.join('\n')}\n};\n${END}`;
}

/** The asset source with its generated block replaced. */
export function withBlock(source, icons) {
  const a = source.indexOf(BEGIN), b = source.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${ASSET} has no generated block (${BEGIN} … ${END})`);
  return source.slice(0, a) + block(icons) + source.slice(b + END.length);
}

function vendor(from) {
  const pkg = JSON.parse(readFileSync(join(from, 'package.json'), 'utf8'));
  if (pkg.name !== 'lucide-static') throw new Error(`${from} is not an unpacked lucide-static package`);
  const dup = NAMES.filter((n, i) => NAMES.indexOf(n) !== i);
  if (dup.length) throw new Error(`listed twice: ${dup.join(', ')}`);
  const missing = NAMES.filter((n) => !existsSync(join(from, 'icons', `${n}.svg`)));
  if (missing.length) throw new Error(`not in lucide-static@${pkg.version}: ${missing.join(', ')}`);
  mkdirSync(join(VENDOR, 'icons'), { recursive: true });
  for (const f of readdirSync(join(VENDOR, 'icons'))) if (!NAMES.includes(f.replace(/\.svg$/, ''))) throw new Error(`vendor/lucide/icons/${f} is not in the curated list: remove it first`);
  for (const n of NAMES) copyFileSync(join(from, 'icons', `${n}.svg`), join(VENDOR, 'icons', `${n}.svg`));
  copyFileSync(join(from, 'LICENSE'), join(VENDOR, 'LICENSE'));
  copyFileSync(join(from, 'README.md'), join(VENDOR, 'UPSTREAM-README.md'));
  const info = { name: pkg.name, version: pkg.version, license: pkg.license, homepage: pkg.homepage, repository: pkg.repository?.url, icons: NAMES.length, packedWith: `npm pack lucide-static@${pkg.version}`, generatedBy: 'node scripts/vendor-icons.mjs --from <unpacked package>' };
  writeFileSync(join(VENDOR, 'VERSION.json'), `${JSON.stringify(info, null, 2)}\n`);
  return pkg.version;
}

const sha = (s) => createHash('sha1').update(s).digest('hex');

if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const from = args.includes('--from') ? args[args.indexOf('--from') + 1] : null;
  if (from) console.log(`vendored lucide-static@${vendor(resolve(from))}: ${NAMES.length} icons`);
  const icons = vendoredIcons();
  const next = withBlock(readFileSync(ASSET, 'utf8'), icons);
  if (args.includes('--check')) {
    if (sha(next) !== sha(readFileSync(ASSET, 'utf8'))) { console.error('assets/kit-icon.js does not match vendor/lucide/icons: run node scripts/vendor-icons.mjs'); process.exit(1); }
    console.log(`kit-icon matches the ${NAMES.length} vendored icons`);
  } else {
    writeFileSync(ASSET, next);
    console.log(`assets/kit-icon.js: ${NAMES.length} icons, ${Buffer.byteLength(block(icons))} bytes of data`);
  }
}
